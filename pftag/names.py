"""Pseudonymous names for templates: the ``dcmname`` function.

``dcmname`` replaces a value with a DICOM-style ``LAST^FIRST`` name generated by
``faker``. Seeded by its argument, the same seed always produces the same name, so a
subject can carry one pseudonym across a study. That is all it guarantees: the name
is a seeded hash wearing a surname, and anyone holding the seed scheme can recompute
it. It is not anonymization; it is a readable stand-in.

Key components:
    - dcmname: the function, registered by ``FunctionRegistry`` when ``faker`` imports

Typical usage:
    %{PatientName|dcmname(study-seed)}^ANON

Dependencies:
    - faker, installed with ``pip install 'pftag[names]'``
"""

from __future__ import annotations

from faker import Faker

from pftag.functions import args_count

DICOM_NAME_SEPARATOR: str = "^"


def dcmname(value: str, args: list[str]) -> str:
    """A DICOM-style ``LAST^FIRST`` name in place of the value.

    Args:
        value: the text being replaced; ignored unless no seed is given, in which
            case it is the seed, so the same value always maps to the same name.
        args: an optional seed.

    Returns:
        ``LAST^FIRST`` in upper case.
    """
    args_count("dcmname", args, 0, 1)
    faker: Faker = Faker()
    faker.seed_instance(args[0] if args else value)
    return f"{faker.last_name().upper()}{DICOM_NAME_SEPARATOR}{faker.first_name().upper()}"
